import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..", "..");
const iconNodesPath = path.join(
  root,
  "node_modules",
  "lucide-static",
  "icon-nodes.json"
);
const runtimeIconTarget = path.join(
  root,
  "force-app",
  "main",
  "default",
  "lwc",
  "newtonSelectorIcon",
  "lucideIconPaths.js"
);
const selectorTarget = path.join(
  root,
  "force-app",
  "main",
  "default",
  "lwc",
  "newtonSelectorFlowCpeIconSelector",
  "iconCatalog.js"
);

const iconNodes = JSON.parse(fs.readFileSync(iconNodesPath, "utf8"));
const iconNames = Object.keys(iconNodes).sort((a, b) => a.localeCompare(b));

function attrToKebabCase(name) {
  return name.replace(/[A-Z]/g, (match) => `-${match.toLowerCase()}`);
}

function escapeAttribute(value) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/"/g, "&quot;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

function nodeToMarkup(node) {
  const [tag, attributes] = node;
  const attrText = Object.entries(attributes)
    .map(
      ([name, value]) => `${attrToKebabCase(name)}="${escapeAttribute(value)}"`
    )
    .join(" ");
  return `<${tag}${attrText ? ` ${attrText}` : ""}></${tag}>`;
}

function humanLabel(name) {
  return name.replace(/-/g, " ");
}

function jsObject(entries, valueFactory) {
  return entries
    .map(
      (name) =>
        `  ${JSON.stringify(name)}: ${JSON.stringify(valueFactory(name))}`
    )
    .join(",\n");
}

const iconPathEntries = jsObject(iconNames, (name) =>
  iconNodes[name].map(nodeToMarkup).join("")
);

const catalogEntries = iconNames
  .map((name) => {
    const entry = { iconName: name, humanLabel: humanLabel(name) };
    return `  ${JSON.stringify(name)}: ${JSON.stringify(entry)}`;
  })
  .join(",\n");

const runtimeIconModule = `// Generated by scripts/icons/generate-lucide-lwc.mjs from lucide-static.
// Do not edit directly.

const DEFAULT_ICON_NAME = "circle-question-mark";

const LUCIDE_ICON_PATHS = Object.freeze({
${iconPathEntries}
});

function normalizeIconName(name) {
  return (name || DEFAULT_ICON_NAME).trim().toLowerCase().replace(/_/g, "-");
}

export function resolveIconContent(name) {
  return (
    LUCIDE_ICON_PATHS[normalizeIconName(name)] ||
    LUCIDE_ICON_PATHS[DEFAULT_ICON_NAME]
  );
}
`;

const selectorModule = `// Generated by scripts/icons/generate-lucide-lwc.mjs from lucide-static.
// Do not edit directly.

const ICONS_BY_NAME = Object.freeze({
${catalogEntries}
});

const ICONS = Object.freeze(Object.values(ICONS_BY_NAME));

export function filterIcons(searchTerm) {
  const term = (searchTerm || "").trim().toLowerCase();
  if (!term) return ICONS;
  return ICONS.filter(
    (entry) =>
      entry.iconName.toLowerCase().includes(term) ||
      entry.humanLabel.toLowerCase().includes(term)
  );
}

export function findIconByName(name) {
  return ICONS_BY_NAME[name] || null;
}
`;

fs.writeFileSync(runtimeIconTarget, runtimeIconModule, "utf8");
fs.writeFileSync(selectorTarget, selectorModule, "utf8");

execFileSync(
  process.execPath,
  [
    path.join(root, "node_modules", "prettier", "bin", "prettier.cjs"),
    "--write",
    runtimeIconTarget,
    selectorTarget
  ],
  { cwd: root, stdio: "inherit" }
);

console.log(
  `Generated ${iconNames.length} Lucide icons for newtonSelectorIcon and newtonSelectorFlowCpeIconSelector.`
);
